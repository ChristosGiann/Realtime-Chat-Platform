import { expect, test } from '@playwright/test'
import type { APIRequestContext, Page } from '@playwright/test'
import { randomUUID } from 'node:crypto'
const api = 'http://localhost:5080'
const password = 'Test-password123!'
function account() { const userName = 'e2e' + randomUUID().replaceAll('-', ''); return { userName, email: `${userName}@example.test`, password } }
async function register(request: APIRequestContext, displayName?: string) {
  const user = account()
  const result = await request.post(`${api}/api/auth/register`, { data: { ...user, displayName } })
  expect(result.status()).toBe(201)
  return { ...user, id: (await result.json()).id as string }
}
async function login(page: Page, email: string, loginPassword = password) {
  await page.goto('/#/login')
  await page.getByLabel('Email', { exact: true }).fill(email)
  await page.getByLabel('Κωδικός', { exact: true }).fill(loginPassword)
  await page.getByRole('button', { name: 'Σύνδεση', exact: true }).click()
}
